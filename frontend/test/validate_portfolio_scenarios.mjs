import assert from "node:assert/strict";
import {build} from "esbuild";
const b=await build({entryPoints:["src/premium/portfolioScenarios.ts"],bundle:true,format:"esm",platform:"node",write:false,logLevel:"silent"});
const {portfolioBootstrap,scalingScenario}=await import("data:text/javascript;base64,"+Buffer.from(b.outputFiles[0].text).toString("base64"));
const trade=(id,day,pnl)=>({id,account_id:"a",strategy:"AORB",t_close:1730000000+day*86400,pnl});
const few=[trade(1,0,100),trade(2,0,-50),trade(3,1,50)];
const abstain=portfolioBootstrap(few);
assert.equal(abstain.eligible,false);
assert.equal(abstain.p50,null);
assert.equal(abstain.breachFrequency,null);
assert.equal(abstain.trainingDays,1);
const many=[];
for(let day=0;day<60;day++)for(let j=0;j<2;j++)
  many.push(trade(2*day+j,day,day%4===0?-90:45));
const a=portfolioBootstrap(many,{balance:5000,paths:500,seed:123,horizonDays:20});
const again=portfolioBootstrap(many,{balance:5000,paths:500,seed:123,horizonDays:20});
assert.equal(a.eligible,true);
assert.equal(a.closings,120);
assert.equal(a.trainingDays,42);
assert.equal(a.holdoutDays,18);
assert.equal(a.paths,500);
assert.equal(a.p50,again.p50);
assert.equal(a.breachFrequency,again.breachFrequency);
assert.ok(a.p05<=a.p50&&a.p50<=a.p95);
assert.ok(a.breachFrequency>=0&&a.breachFrequency<=1);
assert.ok(a.targetFrequency>=0&&a.targetFrequency<=1);
const plan=scalingScenario({existing:5000,accounts25:2,accounts50:1,fee25:250,fee50:400,ratePct:5,splitPct:80,months:12});
assert.equal(plan.nominalFunded,105000);
assert.equal(plan.newNominal,100000);
assert.equal(plan.monthlyWithdrawEstimate,4200);
assert.equal(plan.grossWithdrawHorizon,50400);
assert.equal(plan.cost,900);
assert.equal(plan.afterPurchaseFees,49500);
assert.equal(plan.breakEvenMonths,1);
const incomplete=scalingScenario({accounts25:2,accounts50:0});
assert.equal(incomplete.cost,null);
assert.equal(incomplete.afterPurchaseFees,null);
assert.equal(scalingScenario({accounts25:-1}).valid,false);
assert.equal(scalingScenario({ratePct:999}).valid,false);
console.log("✓ Portfolio scenarios: minimum sample, deterministic bootstrap, FX-free funded nominal and explicit fee abstention");
