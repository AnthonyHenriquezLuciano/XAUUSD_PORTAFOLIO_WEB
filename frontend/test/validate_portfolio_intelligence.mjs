import assert from "node:assert/strict";
import { build } from "esbuild";
const b=await build({entryPoints:["src/premium/portfolioAnalytics.ts"],bundle:true,platform:"node",format:"esm",write:false,logLevel:"silent"});
const x=await import("data:text/javascript;base64,"+Buffer.from(b.outputFiles[0].text).toString("base64"));
const t=(id,account_id,pnl,t_close,strategy="TOK")=>({id,account_id,pnl,t_close,strategy,source:"EA",ticket:id,status:"closed",r:null,lots:.1,side:1});
const trades=[t(1,"a",200,10),t(2,"a",-100,20),t(3,"a",50,30,"AORB"),t(4,"b",-25,25),t(5,"a",700,null),t(6,"a",NaN,40)];
const a=x.byAccountPerformance(trades,["a","b","missing"]);
assert.equal(a[0].net,150);
assert.equal(a[0].trades,3);
assert.equal(a[0].wins,2);
assert.equal(a[0].losses,1);
assert.equal(a[0].maxClosedTradeDrawdown,100);
assert.equal(a[0].winRate,2/3);
assert.equal(a[1].net,-25);
assert.equal(a[2].winRate,null);
assert.equal(a[2].profitFactor,null);
const st=x.byStrategyPerformance(trades);
assert.equal(st[0].strategy,"TOK");
assert.equal(st[0].trades,3);
assert.equal(st.find(v=>v.strategy==="AORB").profitFactor,null,"all wins PF is undefined, not Infinity");
assert.equal(x.portfolioClosedCurve(trades).length,4);
assert.equal(x.portfolioClosedCurve(trades).at(-1).net,125);
const alerts=x.portfolioInsights([{id:"a",connected:false,unknown:true,unprotected:1,blocked:null,dailyBuffer:null,equity:null,stopRisk:null,positions:1}],a);
assert.ok(alerts.some(v=>v.level==="critical"));
assert.ok(alerts.some(v=>v.key==="smallSample"));
assert.deepEqual(x.byStrategyPerformance([]),[]);
console.log("✓ Portfolio Intelligence: closed-only attribution, no invented P&L, strategies and risk guard alerts");
