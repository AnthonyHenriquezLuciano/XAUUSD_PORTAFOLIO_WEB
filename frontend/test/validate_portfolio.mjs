import assert from "node:assert/strict";
import { build } from "esbuild";
const b=await build({entryPoints:["src/premium/portfolioRisk.ts"],bundle:true,platform:"node",format:"esm",write:false,logLevel:"silent"});
const {summarizeAccount,portfolioTotals}=await import("data:text/javascript;base64,"+Buffer.from(b.outputFiles[0].text).toString("base64"));
const now=Date.UTC(2026,9,26,15);
const acc={id:"a",name:"Funded 5k",server:"MT5 Demo"};
const state={account_id:"a",account:{balance:5000,currency:"USD"},risk:{daily_floor:4800,max_floor:4500},ea:{contract:100},
 positions:[{side:1,volume:.1,sl:2300}],orders:[{volume:.2}]};
const live={account_id:"a",bid:2320,ask:2320.2,balance:5000,equity:4950,updated_at:new Date(now-5000).toISOString()};
const r=summarizeAccount(acc,live,state,now);
assert.equal(r.connected,true);
assert.equal(r.unknown,false);
assert.equal(r.dailyBuffer,150);
assert.equal(r.maxBuffer,450);
assert.equal(r.stopRisk,200);
assert.equal(r.unprotected,0);
assert.equal(r.pending,1);
assert.equal(r.positions,1);
const totals=portfolioTotals([r]);
assert.equal(totals.equityUsd,4950);
assert.equal(totals.dailyBufferUsd,150);
assert.equal(totals.stopRiskUsd,200);
assert.equal(totals.estimatedAvailableUsd,0);
assert.equal(totals.connected,1);
const stale=summarizeAccount(acc,{...live,updated_at:new Date(now-60000).toISOString()},state,now);
assert.equal(stale.unknown,true);
assert.equal(portfolioTotals([stale]).estimatedAvailableUsd,null);
const naked=summarizeAccount(acc,live,{...state,positions:[{side:1,volume:.1,sl:0}]},now);
assert.equal(naked.stopRisk,null);
assert.equal(naked.unprotected,1);
assert.equal(portfolioTotals([naked]).estimatedAvailableUsd,null);
const eur=summarizeAccount({id:"b",name:"EU"},live,{...state,account:{currency:"EUR",balance:10000}},now);
assert.equal(portfolioTotals([r,eur]).excluded,1);
assert.equal(portfolioTotals([r,eur]).equityUsd,4950);
const none=summarizeAccount(acc,undefined,undefined,now);
assert.equal(none.connected,false);
assert.equal(none.unknown,true);
assert.equal(none.dailyBuffer,null);
assert.equal(portfolioTotals([none]).equityUsd,0,"no USD accounts contribute 0 by sum convention");
console.log("✓ Portfolio: separate currencies, stale account, stop exposure and conservative aggregated guard");
